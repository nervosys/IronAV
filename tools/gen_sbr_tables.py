#!/usr/bin/env python3
"""Generate crates/ironav-codec/src/aac/sbr_tables.rs from FFmpeg's SBR sources.

Usage: gen_sbr_tables.py FFMPEG/libavcodec > sbr_tables.rs
"""
import os
import re
import sys

root = sys.argv[1]


def read(p):
    return open(os.path.join(root, p), encoding="utf-8").read()


def body(src, name):
    m = re.search(name + r"[^=]*=\s*\{(.*?)\n\};", src, re.S)
    assert m, name
    return m.group(1)


def floats(text):
    return [t for t in re.findall(r"Q31\(\s*([-+0-9.eE]+?)f?\s*\)", text)]


data = read("aacsbrdata.h")
ds = floats(body(data, "sbr_qmf_window_ds"))
us = floats(body(data, "sbr_qmf_window_us"))
assert len(ds) == 320 and len(us) == 640, (len(ds), len(us))
offs = re.findall(r"\{([-0-9, ]+)\}", body(data, "sbr_offset"))
assert len(offs) == 6
noise = floats(body(read("sbrdsp_template.c"), r"ff_sbr_noise_table\)\)\[\]\[2\]"))
assert len(noise) % 2 == 0
tab = read("aac/aacdec_tab.c")
huff = re.findall(r"\{\s*(\d+),\s*(\d+)\s*\}", body(tab, "sbr_huffman_tab\[\]\[2\]"))
counts = [int(x) for x in re.search(r"sbr_huffman_nb_codes\[\]\s*=\s*\{(.*?)\}", tab, re.S).group(1).split(",")]
offsets = [int(x) for x in re.search(r"sbr_vlc_offsets\[10\]\s*=\s*\{(.*?)\}", tab, re.S).group(1).split(",")]
assert sum(counts) == len(huff), (sum(counts), len(huff))

print("// Generated by tools/gen_sbr_tables.py from FFmpeg's aacsbrdata.h, sbrdsp_template.c and aac/aacdec_tab.c.")
print("// Do not edit.")
print()


def arr(name, typ, vals, per=8, doc=None):
    if doc:
        print(f"/// {doc}")
    print(f"pub static {name}: [{typ}; {len(vals)}] = [")
    for i in range(0, len(vals), per):
        print("    " + ", ".join(vals[i:i + per]) + ",")
    print("];")
    print()


def fl(v):
    return v if ("." in v or "e" in v.lower()) else v + ".0"


print("/// Start-band offsets by sample rate class (16, 22.05, 24, 32, 44.1-64, above 64 kHz).")
print("pub static SBR_OFFSET: [[i8; 16]; 6] = [")
for o in offs:
    print("    [" + ", ".join(x.strip() for x in o.split(",")) + "],")
print("];")
print()
arr("QMF_WINDOW_DS", "f32", [fl(v) for v in ds], doc="Analysis QMF window.")
arr("QMF_WINDOW_US", "f32", [fl(v) for v in us], doc="Synthesis QMF window.")
pairs = [(fl(noise[i]), fl(noise[i + 1])) for i in range(0, len(noise), 2)]
print(f"/// Noise table, {len(pairs)} (re, im) pairs.")
print(f"pub static NOISE_TABLE: [[f32; 2]; {len(pairs)}] = [")
for a, b in pairs:
    print(f"    [{a}, {b}],")
print("];")
print()
print("/// Code lengths of the ten Huffman tables, concatenated (sizes in `HUFF_COUNTS`).")
arr("HUFF_LENS", "u8", [h[1] for h in huff], per=16)
print("/// Symbols (before `HUFF_OFFSETS`) in the same order.")
arr("HUFF_SYMBOLS", "u8", [h[0] for h in huff], per=16)
arr("HUFF_COUNTS", "usize", [str(c) for c in counts], per=10, doc="Entries in each table.")
arr("HUFF_OFFSETS", "i32", [str(o) for o in offsets], per=10, doc="Subtracted from a symbol to give the value.")
