#!/usr/bin/env python3
"""Generate crates/ironav-codec/src/aac/ps_tables.rs from FFmpeg's parametric stereo tables.

Usage: gen_ps_tables.py FFMPEG/libavcodec > ps_tables.rs

The Huffman tables (ISO/IEC 14496-3 tables 8.x, as (symbol, length) pairs in code order) and the
k-to-parameter-band maps (tables 8.48 and 8.49) come from aacpsdata.c. The rest of the decoder's tables
are computed at run time from the formulas of the standard.
"""
import os
import re
import sys

root = sys.argv[1]
src = open(os.path.join(root, "aacpsdata.c"), encoding="utf-8").read()


def body(name):
    m = re.search(name + r"[^=]*=\s*\{(.*?)\};", src, re.S)
    assert m, name
    return m.group(1)


pairs = re.findall(r"\{\s*(\d+),\s*(\d+)\s*\}", body(r"aacps_huff_tabs\[\]\[2\]"))
sizes = [int(x) for x in body(r"huff_sizes\[\]").split(",") if x.strip()]
offsets = [int(x) for x in body(r"huff_offset\[\]").split(",") if x.strip()]
k20 = [int(x) for x in body(r"ff_k_to_i_20\[\]").split(",") if x.strip()]
k34 = [int(x) for x in body(r"ff_k_to_i_34\[\]").split(",") if x.strip()]
assert sum(sizes) == len(pairs) and len(sizes) == 10 and len(offsets) == 10
assert len(k20) == 71 and len(k34) == 91, (len(k20), len(k34))

print("// Generated by tools/gen_ps_tables.py from FFmpeg's aacpsdata.c.")
print("// Do not edit.")
print()
print("/// Codes per Huffman table, in the order IID df1, dt1, df0, dt0, ICC df, dt, IPD df, dt, OPD df, dt.")
print("pub static HUFF_SIZES: [usize; 10] = %r;" % sizes)
print()
print("/// Added to each table's symbols.")
print("pub static HUFF_OFFSETS: [i32; 10] = %r;" % offsets)
print()
print("/// (symbol, length in bits) of every code, the tables one after the other; a code is the running sum")
print("/// of 2^-length over the entries before it.")
print("pub static HUFF: [(u8, u8); %d] = [" % len(pairs))
for i in range(0, len(pairs), 8):
    print("    " + ", ".join("(%s, %s)" % p for p in pairs[i:i + 8]) + ",")
print("];")
print()
print("/// Parameter band of each hybrid subband for the 20-band configuration (table 8.48).")
print("pub static K_TO_I_20: [u8; 71] = %r;" % k20)
print()
print("/// Parameter band of each hybrid subband for the 34-band configuration (table 8.49).")
print("pub static K_TO_I_34: [u8; 91] = %r;" % k34)
