#!/usr/bin/env python3
"""Generate parametric stereo lookup tables from 3GPP contribution SP-040428.

Source: https://www.3gpp.org/ftp/tsg_sa/tsg_sa/tsgs_24/docs/pdf/SP-040428.pdf

Pass a layout-preserving text extraction of the PDF. It must include the
hybrid-band maps (PDF pages 38–39) and the Huffman grids (pages 43–45).
Run `python tools/gen_ps_tables.py SP-040428.txt > ps_tables.rs`.
"""

from pathlib import Path
import re
import sys


def table_text(layout, heading, next_heading=None):
    start = layout.index(f"Table {heading} ")
    start = layout.index("\n", start) + 1
    stop = layout.index(next_heading, start) if next_heading else len(layout)
    return layout[start:stop]


def huffman_columns(rows, first, count):
    # Some tables print two groups of index, frequency code and time code on one line.
    row = re.compile(r"\s*(?:-?\d+\s+[01]+\s+[01]+\s*){1,2}")
    columns = ({}, {})
    for line in rows.splitlines():
        if not row.fullmatch(line):
            continue
        cells = line.split()
        for offset in range(0, len(cells), 3):
            index, frequency, time = cells[offset:offset + 3]
            index = int(index)
            for column, word in zip(columns, (frequency, time)):
                if index in column:
                    raise ValueError(f"Repeated index {index} in Huffman grid")
                column[index] = word

    expected = range(first, first + count)
    for column in columns:
        if sorted(column) != list(expected):
            raise ValueError(f"Expected Huffman indices {first} through {first + count - 1}")
        words = list(column.values())
        if any(a != b and b.startswith(a) for a in words for b in words) or len(set(words)) != count:
            raise ValueError("Huffman grid is not prefix-free")
        if sum(1 << (20 - len(word)) for word in words) != 1 << 20:
            raise ValueError("Huffman grid is incomplete")
    return ([column[index] for index in expected] for column in columns)


def band_map(rows, bands, size):
    row = re.compile(r"\s*(\d+)(?:[-–](\d+))?\s+\d+(?:[-–]\d+)?\s+(\d+)\s*\*?(?:\s+(?:Sub QMF|QMF \(only\)))?\s*")
    mapping = []
    for line in rows.splitlines():
        match = row.fullmatch(line)
        if not match:
            continue
        first, last, band = match.groups()
        begin, end, parameter = int(first), int(last or first), int(band)
        if begin != len(mapping) or end < begin or parameter >= bands:
            raise ValueError(f"Invalid hybrid-band row: {line.strip()}")
        mapping.extend([parameter] * (end - begin + 1))
    if len(mapping) != size or set(mapping) != set(range(bands)):
        raise ValueError(f"Expected {size} subbands across {bands} parameter bands")
    return mapping


def generate(layout):
    maps = [
        band_map(table_text(layout, "8.22", "Table 8.23 -"), 20, 71),
        band_map(table_text(layout, "8.23", "8.6.1.6.4 Interpolation"), 34, 91),
    ]
    # The grid column headers list frequency first, including Table 8.B.5.
    appendix = layout[layout.index("Huffman table overview:"):]
    groups = [("IID fine", -30, 61), ("IID coarse", -14, 29), ("ICC", -7, 15), ("IPD", 0, 8), ("OPD", 0, 8)]
    books = []
    for number, (label, first, count) in enumerate(groups, start=3):
        end = f"Table 8.B.{number + 1} " if number < 7 else None
        rows = table_text(appendix, f"8.B.{number}", end)
        for direction, words in zip(("frequency", "time"), huffman_columns(rows, first, count)):
            books.append((f"{label}, {direction}", first, words))

    print("// Generated by tools/gen_ps_tables.py from 3GPP SP-040428, Annex B and Tables 8.22–8.23.")
    print()
    print("/// Codewords in signed delta order, with each book's first delta and each word's length.")
    print("pub(super) static HUFFMAN: [(i32, &[(u8, u32)]); 10] = [")
    for name, first, words in books:
        print(f"    // {name}")
        print(f"    ({first}, &[")
        for offset in range(0, len(words), 6):
            print("        " + ", ".join(f"({len(word)}, 0x{int(word, 2):x})" for word in words[offset:offset + 6]) + ",")
        print("    ]),")
    print("];")
    for bands, mapping in zip((20, 34), maps):
        print()
        print(f"/// Parameter band for each hybrid subband in the {bands}-band layout.")
        print(f"pub(super) static K_TO_I_{bands}: [u8; {len(mapping)}] = [")
        for offset in range(0, len(mapping), 20):
            print("    " + ", ".join(map(str, mapping[offset:offset + 20])) + ",")
        print("];")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(f"Usage: {sys.argv[0]} SP-040428.txt")
    generate(Path(sys.argv[1]).read_text(encoding="utf-8-sig"))
