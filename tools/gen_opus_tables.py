#!/usr/bin/env python3
"""Generate crates/ironav-codec/src/opus/tables.rs from FFmpeg's libavcodec/opus/tab.c.

Usage: gen_opus_tables.py PATH/TO/ffmpeg/libavcodec/opus/tab.c > tables.rs

Every `const <type> name[dims] = { ... };` array is flattened, evaluated (the float entries are
small constant expressions) and written back out with its declared shape. The pointer table
`ff_celt_pvq_u_row` and the macro-built `ff_opus_deemph_weights` are not arrays of literals, so
they are rebuilt in Rust instead.
"""
import re
import struct
import sys

TYPES = {"uint8_t": "u8", "uint16_t": "u16", "uint32_t": "u32", "int8_t": "i8", "int16_t": "i16", "int": "i32", "float": "f32"}
SKIP = {"ff_celt_pvq_u_row", "ff_opus_deemph_weights"}

src = open(sys.argv[1], encoding="utf-8").read()
src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
src = re.sub(r"//[^\n]*", "", src)

src = re.sub(r"DECLARE_ALIGNED\(\d+,\s*const\s+(\w+),\s*(\w+)\)", lambda m: f"const {m.group(1)} {m.group(2)}", src)
decl = re.compile(r"(?:static\s+)?const\s+(\w+)\s+(?:\*\s*const\s+)?(\w+)((?:\[\s*\w*\s*\])+)\s*=\s*\{")


def balanced(text, start):
    depth = 0
    for i in range(start, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[start + 1 : i]
    raise ValueError("unbalanced braces")


def fmt_float(v):
    f = struct.unpack("f", struct.pack("f", v))[0]
    s = "%.9g" % f
    if "e" not in s and "." not in s and "inf" not in s:
        s += ".0"
    return s


out = []
for m in decl.finditer(src):
    ctype, name, dims = m.group(1), m.group(2), m.group(3)
    if name in SKIP or ctype not in TYPES:
        continue
    body = balanced(src, m.end() - 1)
    flat = re.sub(r"[{}]", " ", body)
    items = [t.strip() for t in flat.split(",") if t.strip()]
    rust = TYPES[ctype]
    vals = []
    for t in items:
        t = re.sub(r"(?<=[\d.])f\b", "", t)
        t = re.sub(r"(?<=\d)u\b", "", t)
        v = eval(t, {"__builtins__": {}}, {})
        vals.append(v)
    shape = [int(d) for d in re.findall(r"\[\s*(\d*)\s*\]", dims) if d]
    total = len(vals)
    if not shape:
        shape = [total]
    else:
        prod = 1
        for d in shape:
            prod *= d
        if prod > total and total % shape[-1] == 0:
            vals += [0] * (prod - total)  # rows left out of the initialiser are zero, as in C
            total = prod
        if prod != total:
            sys.exit(f"{name}: declared {shape} = {prod} but has {total} values")

    def lit(v):
        return fmt_float(v) if rust == "f32" else str(int(v))

    def emit(vals, shape, indent):
        pad = "    " * indent
        if len(shape) == 1:
            line = ", ".join(lit(v) for v in vals)
            # wrap long rows
            if len(line) > 110:
                chunks, cur = [], []
                width = 0
                for v in vals:
                    s = lit(v)
                    if width + len(s) + 2 > 108:
                        chunks.append(", ".join(cur))
                        cur, width = [], 0
                    cur.append(s)
                    width += len(s) + 2
                chunks.append(", ".join(cur))
                return "[\n" + "".join(f"{pad}    {c},\n" for c in chunks) + pad + "]"
            return "[" + line + "]"
        step = len(vals) // shape[0]
        rows = [emit(vals[i * step : (i + 1) * step], shape[1:], indent + 1) for i in range(shape[0])]
        return "[\n" + "".join(f"{pad}    {r},\n" for r in rows) + pad + "]"

    ty = rust
    for d in reversed(shape):
        ty = f"[{ty}; {d}]"
    const = name.replace("ff_", "", 1).upper()
    out.append(f"pub static {const}: {ty} = {emit(vals, shape, 0)};\n")

# The frame durations (in samples at 48 kHz) of the 32 TOC configurations.
print("// Generated by tools/gen_opus_tables.py from FFmpeg's libavcodec/opus/tab.c. Do not edit.")
print("#![allow(clippy::all)]\n")
print("".join(o + "\n" for o in out))
