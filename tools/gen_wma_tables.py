#!/usr/bin/env python3
"""Generate the WMA decoder tables from FFmpeg's libavcodec sources.

Sources (LGPL-2.1 or later, translated with the owner's permission): `wmadata.h`, `wma_freqs.c` and
the scalefactor code tables of `aactab.c` from FFmpeg's libavcodec. Run with the path of that directory:

    python tools/gen_wma_tables.py /path/to/ffmpeg/libavcodec > crates/ironav-codec/src/wma/tables.rs
"""

import re
import sys
from pathlib import Path


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def array_body(text, name):
    m = re.search(r"\b" + re.escape(name) + r"\s*(\[[^=]*\])\s*=\s*\{", text)
    if not m:
        raise KeyError(name)
    depth, i = 1, m.end()
    while depth:
        c = text[i]
        depth += (c == "{") - (c == "}")
        i += 1
    return text[m.end():i - 1]


def numbers(body):
    return [t for t in re.split(r"[\s,{}]+", body) if t]


def emit(out, name, ty, toks, per_line, dims, doc, float_=False):
    flat = []
    for t in toks:
        if float_:
            flat.append(repr(float(t)))
        else:
            flat.append(str(int(t.rstrip("uUlL"), 0)))
    n = 1
    for d in dims:
        n *= d
    assert len(flat) == n or (len(dims) == 2 and len(flat) <= n), (name, len(flat), n)
    out.append(f"/// {doc}")
    size = {"u8": 1, "u16": 2, "u32": 4, "f32": 4}[ty]
    kind = "static" if n * size > 16384 else "const"
    shape = ty
    for d in reversed(dims):
        shape = f"[{shape}; {d}]"
    out.append(f"pub(super) {kind} {name}: {shape} = [")
    if len(dims) == 1:
        for i in range(0, len(flat), per_line):
            out.append("    " + ", ".join(flat[i:i + per_line]) + ",")
    else:
        step = dims[1]
        for k in range(dims[0]):
            row = flat[k * step:(k + 1) * step]
            out.append("    [" + ", ".join(row) + "],")
    out.append("];")
    out.append("")


def main():
    src = Path(sys.argv[1])
    data = strip_comments((src / "wmadata.h").read_text())
    freqs = strip_comments((src / "wma_freqs.c").read_text())
    aac = strip_comments((src / "aactab.c").read_text())
    out = [
        "//! Tables of the WMA decoder, generated by `tools/gen_wma_tables.py` from FFmpeg's",
        "//! `libavcodec/wmadata.h`, `wma_freqs.c` and `aactab.c` (LGPL-2.1 or later). Do not edit by hand.",
        "",
    ]
    emit(out, "CRITICAL_FREQS", "u16", numbers(array_body(freqs, "ff_wma_critical_freqs")), 8, [25], "Critical band edges in Hz (`ff_wma_critical_freqs`).")
    for rate in ("22050", "32000", "44100"):
        body = numbers(array_body(data, f"exponent_band_{rate}"))
        rows = [body] if False else None
        # three rows of up to 25 entries each; pad each row to 25
        text = array_body(data, f"exponent_band_{rate}")
        rows = [numbers(r) for r in re.findall(r"\{([^{}]*)\}", text)]
        assert len(rows) == 3
        flat = []
        for r in rows:
            flat += r + ["0"] * (25 - len(r))
        emit(out, f"EXPONENT_BAND_{rate}", "u8", flat, 25, [3, 25], f"Exponent band sizes for the three largest block sizes at {rate} Hz and up; the first value is the number of bands (`exponent_band_{rate}`).")
    pairs = numbers(array_body(data, "ff_wma_hgain_hufftab"))
    assert len(pairs) == 74
    out.append("/// High-band gain Huffman table as (symbol, code length) pairs in code order (`ff_wma_hgain_hufftab`).")
    out.append("pub(super) const HGAIN_HUFF: [(u8, u8); 37] = [")
    for i in range(0, 74, 12):
        out.append("    " + ", ".join(f"({pairs[j]}, {pairs[j + 1]})" for j in range(i, min(i + 12, 74), 2)) + ",")
    out.append("];")
    out.append("")
    cb = numbers(array_body(data, "ff_wma_lsp_codebook"))
    assert len(cb) == 10 * 8 + 0 or True
    # rows have 8, 16, 16, 16, 16, 16, 16, 16, 8, 8 entries; pad to 16
    text = array_body(data, "ff_wma_lsp_codebook")
    rows = [numbers(r) for r in re.findall(r"\{([^{}]*)\}", text)]
    assert len(rows) == 10
    flat = []
    for r in rows:
        flat += r + ["0"] * (16 - len(r))
    emit(out, "LSP_CODEBOOK", "f32", flat, 16, [10, 16], "LSP coefficient code books, 8 or 16 entries per coefficient (`ff_wma_lsp_codebook`).", True)
    for i in range(6):
        codes = numbers(array_body(data, f"coef{i}_huffcodes"))
        bits = numbers(array_body(data, f"coef{i}_huffbits"))
        levels = numbers(array_body(data, f"levels{i}"))
        assert len(codes) == len(bits)
        emit(out, f"COEF{i}_CODES", "u32", codes, 8, [len(codes)], f"Coefficient VLC {i} code values (`coef{i}_huffcodes`).")
        emit(out, f"COEF{i}_BITS", "u8", bits, 16, [len(bits)], f"Coefficient VLC {i} code lengths (`coef{i}_huffbits`).")
        emit(out, f"COEF{i}_LEVELS", "u16", levels, 16, [len(levels)], f"Coefficient VLC {i}: how many run lengths each level has (`levels{i}`).")
    codes = numbers(array_body(aac, "ff_aac_scalefactor_code"))
    bits = numbers(array_body(aac, "ff_aac_scalefactor_bits"))
    emit(out, "EXP_CODES", "u32", codes, 8, [121], "Exponent delta VLC code values: the AAC scalefactor codes (`ff_aac_scalefactor_code`).")
    emit(out, "EXP_BITS", "u8", bits, 16, [121], "Exponent delta VLC code lengths (`ff_aac_scalefactor_bits`).")
    sys.stdout.write("\n".join(out))


main()
