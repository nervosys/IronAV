#!/usr/bin/env python3
"""Generate crates/ironav-codec/src/jpeg/tables.rs from FFmpeg's jpegtabs.h (the standard
Huffman tables of ITU T.81 annex K).

Usage: gen_jpeg_tables.py FFMPEG/libavcodec > tables.rs
"""
import os
import re
import sys

src = open(os.path.join(sys.argv[1], "jpegtabs.h"), encoding="utf-8").read()


def arr(name):
    m = re.search(name + r"[^=]*=\s*\{(.*?)\};", src, re.S)
    assert m, name
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    return [int(t, 0) for t in re.findall(r"0x[0-9a-fA-F]+|\d+", body)]


print("// Generated by tools/gen_jpeg_tables.py from FFmpeg's jpegtabs.h. Do not edit.")
print("// Each `BITS` table lists the number of codes of length 1 to 16; `VALS` the symbols in code order.")
print()
for rust, c in [
    ("DC_LUMA", "ff_mjpeg_bits_dc_luminance"),
    ("DC_CHROMA", "ff_mjpeg_bits_dc_chrominance"),
    ("AC_LUMA", "ff_mjpeg_bits_ac_luminance"),
    ("AC_CHROMA", "ff_mjpeg_bits_ac_chrominance"),
]:
    bits = arr(c)
    assert len(bits) == 17
    print(f"pub static {rust}_BITS: [u8; 16] = {bits[1:]};")
vals = {
    "DC": arr("ff_mjpeg_val_dc"),
    "AC_LUMA": arr("ff_mjpeg_val_ac_luminance"),
    "AC_CHROMA": arr("ff_mjpeg_val_ac_chrominance"),
}
assert len(vals["DC"]) == 12 and len(vals["AC_LUMA"]) == 162 and len(vals["AC_CHROMA"]) == 162
for k, v in vals.items():
    print(f"pub static {k}_VALS: [u8; {len(v)}] = {v};")
