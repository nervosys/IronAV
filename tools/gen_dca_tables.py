#!/usr/bin/env python3
"""Generate the DTS core decoder tables from FFmpeg's libavcodec sources.

Sources (LGPL-2.1 or later, translated with the owner's permission): `dcadata.c` and `dcahuff.c`
from FFmpeg's libavcodec. Run with the path of that directory:

    python tools/gen_dca_tables.py /path/to/ffmpeg/libavcodec > crates/ironav-codec/src/dts/tables.rs
"""

import re
import sys
from pathlib import Path


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def array_body(text, name):
    m = re.search(r"\b" + re.escape(name) + r"\)?\s*(\[[^=]*\])\s*=\s*\{", text)
    if not m:
        raise KeyError(name)
    depth, i = 1, m.end()
    while depth:
        c = text[i]
        depth += (c == "{") - (c == "}")
        i += 1
    return text[m.end():i - 1]


def numbers(body, scale=False):
    if scale:
        body = re.sub(r"SCALE\(([^)]*)\)", lambda m: repr(float(m.group(1)) / (256.0 * 32768.0)), body)
    toks = [t for t in re.split(r"[\s,{}]+", body) if t]
    return toks


def emit(out, name, ty, toks, per_line, dims, doc, float_=False):
    flat = []
    for t in toks:
        t = t.rstrip("fFuUlL") if not float_ else t
        if float_:
            v = float(t)
            flat.append(repr(v))
        else:
            flat.append(str(int(t, 0)))
    n = 1
    for d in dims:
        n *= d
    assert len(flat) == n, (name, len(flat), n)
    shape = ty
    for d in reversed(dims):
        shape = f"[{shape}; {d}]"
    out.append(f"/// {doc}")
    # clippy wants a static for a big table (more than 16 KiB), so it is not copied at each use
    kind = "static" if n * (4 if float_ else 2) > 16384 else "const"
    out.append(f"pub(super) {kind} {name}: {shape} = [")
    inner = dims[-1]

    def rows(depth, items):
        pad = "    " * (depth + 1)
        if depth == len(dims) - 1:
            for i in range(0, len(items), per_line):
                out.append(pad + ", ".join(items[i:i + per_line]) + ",")
        else:
            step = len(items) // dims[depth]
            for k in range(dims[depth]):
                row = items[k * step:(k + 1) * step]
                if depth == len(dims) - 2:
                    out.append(pad + "[" + ", ".join(row) + "],")
                else:
                    out.append(pad + "[")
                    rows(depth + 1, row)
                    out.append(pad + "],")

    rows(0, flat)
    out.append("];")
    out.append("")


def main():
    src = Path(sys.argv[1])
    data = strip_comments((src / "dcadata.c").read_text())
    huff_raw = (src / "dcahuff.c").read_text()
    huff = strip_comments(huff_raw)
    out = [
        "//! Tables of the DTS core decoder, generated by `tools/gen_dca_tables.py` from FFmpeg's",
        "//! `libavcodec/dcadata.c` and `dcahuff.c` (LGPL-2.1 or later). Do not edit by hand.",
        "",
    ]
    emit(out, "BIT_RATES", "u32", numbers(array_body(data, "ff_dca_bit_rates")), 6, [32], "Transmission bit rates by code (`dcadata.c`, `ff_dca_bit_rates`); 1, 2 and 3 are open, variable and lossless.")
    emit(out, "ADPCM_VB", "i16", numbers(array_body(data, "ff_dca_adpcm_vb")), 4, [4096, 4], "ADPCM prediction coefficient vectors, Q13 (`ff_dca_adpcm_vb`).")
    emit(out, "SCALE_FACTOR_QUANT6", "u32", numbers(array_body(data, "ff_dca_scale_factor_quant6")), 8, [64], "6-bit root-square scale factors (`ff_dca_scale_factor_quant6`).")
    emit(out, "SCALE_FACTOR_QUANT7", "u32", numbers(array_body(data, "ff_dca_scale_factor_quant7")), 8, [128], "7-bit root-square scale factors (`ff_dca_scale_factor_quant7`).")
    emit(out, "JOINT_SCALE_FACTORS", "u32", numbers(array_body(data, "ff_dca_joint_scale_factors")), 8, [129], "Joint intensity scale factors (`ff_dca_joint_scale_factors`).")
    emit(out, "SCALE_FACTOR_ADJ", "u32", numbers(array_body(data, "ff_dca_scale_factor_adj")), 4, [4], "Scale factor adjustments for Huffman-coded samples (`ff_dca_scale_factor_adj`).")
    emit(out, "QUANT_LEVELS", "u32", numbers(array_body(data, "ff_dca_quant_levels")), 8, [32], "Quantiser level counts by bit allocation index (`ff_dca_quant_levels`).")
    emit(out, "LOSSY_QUANT", "u32", numbers(array_body(data, "ff_dca_lossy_quant")), 8, [32], "Quantiser step sizes, 20 bits (`ff_dca_lossy_quant`).")
    emit(out, "LOSSLESS_QUANT", "u32", numbers(array_body(data, "ff_dca_lossless_quant")), 8, [32], "Quantiser step sizes for lossless streams, 20 bits (`ff_dca_lossless_quant`).")
    emit(out, "HIGH_FREQ_VQ", "i8", numbers(array_body(data, "ff_dca_high_freq_vq")), 16, [1024, 32], "High-frequency vector quantisation code book (`ff_dca_high_freq_vq`).")
    emit(out, "FIR_32_PERFECT", "f32", numbers(array_body(data, "ff_dca_fir_32bands_perfect")), 6, [512], "Perfect-reconstruction 32-band synthesis window (`ff_dca_fir_32bands_perfect`).", True)
    emit(out, "FIR_32_NONPERFECT", "f32", numbers(array_body(data, "ff_dca_fir_32bands_nonperfect")), 6, [512], "Non-perfect-reconstruction 32-band synthesis window (`ff_dca_fir_32bands_nonperfect`).", True)
    emit(out, "LFE_FIR_64", "f32", numbers(array_body(data, "ff_dca_lfe_fir_64"), True), 6, [256], "LFE interpolation filter for 64x (`ff_dca_lfe_fir_64`, scaled as there).", True)
    emit(out, "LFE_FIR_128", "f32", numbers(array_body(data, "ff_dca_lfe_fir_128"), True), 6, [256], "LFE interpolation filter for 128x (`ff_dca_lfe_fir_128`, scaled as there).", True)

    # Huffman code tables: (symbol, length) pairs in code order (`ff_dca_vlc_src_tables`), up to the
    # transition mode tables; the LBR tables after them are not used.
    body = array_body(huff, "ff_dca_vlc_src_tables")
    pairs = re.findall(r"\{\s*(\d+)\s*,\s*(\d+)\s*\}", body)
    # 3 + 3*(5+7+9+13) + 7*(17+25+33+65+129) + 5*12 + 5*129 + 4*4
    count = 3 + 3 * (5 + 7 + 9 + 13) + 7 * (17 + 25 + 33 + 65 + 129) + 5 * 12 + 5 * 129 + 4 * 4
    pairs = pairs[:count]
    assert len(pairs) == count, len(pairs)
    out.append("/// Huffman tables as (symbol, code length) pairs, one table after another, in code order")
    out.append("/// (`ff_dca_vlc_src_tables`): the quantisation index tables, bit allocation, scale factor and")
    out.append("/// transition mode tables, in the order `dcahuff.c` initialises them.")
    out.append(f"pub(super) const VLC_SRC: [(u8, u8); {count}] = [")
    for i in range(0, count, 8):
        out.append("    " + ", ".join(f"({a}, {b})" for a, b in pairs[i:i + 8]) + ",")
    out.append("];")
    out.append("")
    # maxbits table for completeness is not needed: the decoder searches by code.
    sys.stdout.write("\n".join(out))


main()
