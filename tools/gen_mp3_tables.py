#!/usr/bin/env python3
"""Generate crates/ironav-codec/src/mp3/tables.rs from FFmpeg's libavcodec/mpegaudiodec_common.c and
libavcodec/mpegaudiodsp_data.c.

Usage: gen_mp3_tables.py FFMPEG/libavcodec > tables.rs

Every array named in WANTED is flattened and written back out with its declared shape.
"""
import os
import re
import sys

WANTED = {
    "mpa_hufflens": "u8",
    "mpa_huffsymbols": "u8",
    "mpa_huff_sizes_minus_one": "u8",
    "ff_mpa_huff_data": "u8",
    "mpa_quad_codes": "u8",
    "mpa_quad_bits": "u8",
    "ff_band_size_long": "u8",
    "ff_band_size_short": "u8",
    "ff_mpa_pretab": "u8",
    "ff_slen_table": "u8",
    "ff_lsf_nsf_table": "u8",
    "ff_mpa_enwindow": "i32",
}
RENAME = {"mpa_hufflens": "HUFF_LENS", "mpa_huffsymbols": "HUFF_SYMBOLS", "mpa_huff_sizes_minus_one": "HUFF_SIZES_MINUS_ONE",
          "ff_mpa_huff_data": "HUFF_DATA", "mpa_quad_codes": "QUAD_CODES", "mpa_quad_bits": "QUAD_BITS",
          "ff_band_size_long": "BAND_SIZE_LONG", "ff_band_size_short": "BAND_SIZE_SHORT", "ff_mpa_pretab": "PRETAB",
          "ff_slen_table": "SLEN", "ff_lsf_nsf_table": "LSF_NSF", "ff_mpa_enwindow": "ENWINDOW"}

d = sys.argv[1]
src = ""
for f in ("mpegaudiodec_common.c", "mpegaudiodsp_data.c"):
    src += open(os.path.join(d, f), encoding="utf-8").read() + "\n"
src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
src = re.sub(r"//[^\n]*", "", src)
decl = re.compile(r"const\s+(?:u?int\d+_t)\s+(\w+)((?:\[\s*\w*\s*\])+)\s*=\s*\{", re.S)


def balanced(text, start):
    depth = 0
    for i in range(start, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[start + 1:i]
    raise ValueError


def shape(body):
    """Dimensions of a nested brace initialiser."""
    def parse(s):
        s = s.strip()
        items, depth, cur = [], 0, ""
        for ch in s:
            if ch == "{":
                depth += 1
            if ch == "}":
                depth -= 1
            if ch == "," and depth == 0:
                items.append(cur)
                cur = ""
            else:
                cur += ch
        if cur.strip():
            items.append(cur)
        return items
    items = parse(body)
    if items and items[0].strip().startswith("{"):
        inner = [shape(balanced(i.strip(), 0)) for i in items]
        return [len(items)] + inner[0][0], [v for i in inner for v in i[1]]
    return [len(items)], [int(i.strip(), 0) for i in items]


out = ["// Generated by tools/gen_mp3_tables.py from FFmpeg's libavcodec/mpegaudiodec_common.c and mpegaudiodsp_data.c.", "// Do not edit.", ""]
found = set()
for m in decl.finditer(src):
    name = m.group(1)
    if name not in WANTED or name in found:
        continue
    found.add(name)
    body = balanced(src, m.end() - 1)
    dims, vals = shape(body)
    ty = WANTED[name]
    t = ty
    for dim in reversed(dims):
        t = f"[{t}; {dim}]"
    flat = ", ".join(str(v) for v in vals)
    # nest the flat list into the declared shape
    def nest(vs, ds):
        if len(ds) == 1:
            return "[" + ", ".join(str(v) for v in vs) + "]"
        step = len(vs) // ds[0]
        return "[" + ",\n".join(nest(vs[i * step:(i + 1) * step], ds[1:]) for i in range(ds[0])) + "]"
    out.append(f"pub static {RENAME[name]}: {t} = {nest(vals, dims)};")
    out.append("")
missing = set(WANTED) - found
assert not missing, missing
print("\n".join(out))
