#!/usr/bin/env python3
"""Generates crates/ironav-codec/src/h264/tables.rs from FFmpeg's libavcodec sources.

Usage: gen_h264_tables.py FFMPEG/libavcodec > tables.rs

The tables are constants of ITU-T H.264 (CABAC context initialisation values, CAVLC code
tables, default scaling lists, loop-filter thresholds), read here out of FFmpeg's C source so
nothing is typed in by hand.
"""
import re
import sys

src = sys.argv[1]


def read(name):
    return open(f"{src}/{name}", encoding="utf-8").read()


def strip(text):
    text = re.sub(r"//.*", "", text)
    return re.sub(r"/\*.*?\*/", "", text, flags=re.S)


def grab(file, name, nth=0):
    """The flat list of integers in the initialiser of the C array `name`."""
    t = strip(read(file))
    starts = [m.start() for m in re.finditer(r"\b" + re.escape(name) + r"\b\)?(?:\s*\[[^\]]*\])+\s*=", t)]
    i = starts[nth]
    j = t.index("{", i)
    depth, k = 0, j
    while True:
        if t[k] == "{":
            depth += 1
        elif t[k] == "}":
            depth -= 1
            if depth == 0:
                break
        k += 1
    body = t[j + 1:k].replace("{", " ").replace("}", " ")
    out = []
    for el in body.split(","):
        el = el.strip()
        if el:
            out.append(eval(el, {}, {}))  # plain integer arithmetic such as "105+15" or "2 + 3 * 8"
    return out


def grab_rows(file, name, width, nrows):
    """Like grab, for an array of rows that may be shorter than `width`; rows are zero-padded."""
    t = strip(read(file))
    m = re.search(r"\b" + re.escape(name) + r"\b(?:\s*\[[^\]]*\])+\s*=", t)
    j = t.index("{", m.start())
    depth, k = 0, j
    while True:
        if t[k] == "{":
            depth += 1
        elif t[k] == "}":
            depth -= 1
            if depth == 0:
                break
        k += 1
    rows = re.findall(r"\{([^{}]*)\}", t[j + 1:k])
    out = []
    for r in rows:
        vals = [eval(e.strip(), {}, {}) for e in r.split(",") if e.strip()]
        out += vals + [0] * (width - len(vals))
    return out + [0] * (nrows * width - len(out))


def rust(name, ty, vals, dims):
    def nest(v, d):
        if len(d) == 1:
            return "[" + ", ".join(str(x) for x in v) + "]"
        step = len(v) // d[0]
        return "[" + ",\n    ".join(nest(v[i * step:(i + 1) * step], d[1:]) for i in range(d[0])) + "]"

    t = "".join(f"[{ty}; {n}]"[::1] for n in [])  # unused
    sig = ty
    for n in reversed(dims):
        sig = f"[{sig}; {n}]"
    total = 1
    for n in dims:
        total *= n
    assert len(vals) == total, (name, len(vals), total)
    print(f"pub const {name}: {sig} = {nest(vals, dims)};\n")


print("//! Generated by tools/gen_h264_tables.py from FFmpeg's libavcodec; do not edit by hand.\n")
print("#![allow(clippy::all)]\n")

cabac = "h264_cabac.c"
rust("CABAC_INIT_I", "i8", grab(cabac, "cabac_context_init_I"), [1024, 2])
rust("CABAC_INIT_PB", "i8", grab(cabac, "cabac_context_init_PB"), [3, 1024, 2])
rust("SIG_OFF", "u16", grab(cabac, "significant_coeff_flag_offset"), [2, 14])
rust("LAST_OFF", "u16", grab(cabac, "last_coeff_flag_offset"), [2, 14])
rust("ABS_OFF", "u16", grab(cabac, "coeff_abs_level_m1_offset"), [14])
rust("SIG_OFF_8X8", "u8", grab(cabac, "significant_coeff_flag_offset_8x8"), [2, 63])
rust("ABS1_CTX", "u8", grab(cabac, "coeff_abs_level1_ctx"), [8])
rust("ABSGT1_CTX", "u8", grab(cabac, "coeff_abs_levelgt1_ctx"), [2, 8])
rust("ABS_TRANSITION", "u8", grab(cabac, "coeff_abs_level_transition"), [2, 8])

# the packed arithmetic-coder tables: 512 shift entries, then the LPS range for each of the four
# range quarters indexed by 2 * state + mps, then the state transitions, then the 8x8 "last" offsets
packed = grab("cabac.c", "ff_h264_cabac_tables")
lps = [[packed[512 + 128 * q + 2 * p] & 255 for q in range(4)] for p in range(64)]
assert lps[0] == [128, 176, 208, 240] and lps[63] == [2, 2, 2, 2], lps[0]
rust("LPS_RANGE", "u8", [x for row in lps for x in row], [64, 4])
last8 = packed[1280:1280 + 63]
rust("LAST_OFF_8X8", "u8", [x & 255 for x in last8], [63])

cavlc = "h264_cavlc.c"
for n, d in [("coeff_token_len", [4, 68]), ("coeff_token_bits", [4, 68]), ("chroma_dc_coeff_token_len", [20]),
             ("chroma_dc_coeff_token_bits", [20]), ("total_zeros_len", [16, 16]), ("total_zeros_bits", [16, 16]),
             ("chroma_dc_total_zeros_len", [3, 4]), ("chroma_dc_total_zeros_bits", [3, 4]), ("run_len", [7, 16]),
             ("run_bits", [7, 16])]:
    rust(n.upper(), "u8", grab_rows(cavlc, n, d[-1], d[0]) if len(d) == 2 and d[0] != 4 else grab(cavlc, n), d)

rust("GOLOMB_TO_INTRA4X4_CBP", "u8", grab("h264data.c", "ff_h264_golomb_to_intra4x4_cbp"), [48])
rust("GOLOMB_TO_INTER_CBP", "u8", grab("h264data.c", "ff_h264_golomb_to_inter_cbp"), [48])
rust("DEQUANT4_COEFF_INIT", "u8", grab("h264data.c", "ff_h264_dequant4_coeff_init"), [6, 3])
rust("DEQUANT8_COEFF_INIT_SCAN", "u8", grab("h264data.c", "ff_h264_dequant8_coeff_init_scan"), [16])
rust("DEQUANT8_COEFF_INIT", "u8", grab("h264data.c", "ff_h264_dequant8_coeff_init"), [6, 6])
rust("DEFAULT_SCALING4", "u8", grab("h264_ps.c", "default_scaling4"), [2, 16])
rust("DEFAULT_SCALING8", "u8", grab("h264_ps.c", "default_scaling8"), [2, 64])
rust("ZIGZAG_DIRECT", "u8", grab("mathtables.c", "ff_zigzag_direct"), [64])
cav8 = grab("h264_slice.c", "zigzag_scan8x8_cavlc")
rust("ZIGZAG_8X8_CAVLC", "u8", cav8[:64], [64])

# loop-filter thresholds: the tables are padded by 52 entries on each side for the QP offsets;
# the middle 52 entries are the ones for QP 0 to 51
a = grab("h264_loopfilter.c", "alpha_table")
b = grab("h264_loopfilter.c", "beta_table")
tc = grab("h264_loopfilter.c", "tc0_table")
rust("ALPHA", "u8", a[52:104], [52])
rust("BETA", "u8", b[52:104], [52])
rust("TC0", "i8", tc[52 * 4:104 * 4], [52, 4])
