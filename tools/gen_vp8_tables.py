#!/usr/bin/env python3
"""Generate crates/ironav-codec/src/vp8/tables.rs from FFmpeg's VP8 data files.

Usage: gen_vp8_tables.py FFMPEG/libavcodec > tables.rs
"""
import os
import re
import sys

root = sys.argv[1]


def read(p):
    return open(os.path.join(root, p), encoding="utf-8").read()


def body(src, name):
    m = re.search(name + r"[^=]*=\s*\{(.*?)\n\};", src, re.S)
    assert m, name
    return m.group(1)


def nums(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return [int(t) for t in re.findall(r"-?\d+", text)]


data = read("vp8data.h")
cdat = read("vp8data.c")

out = []


def arr(name, typ, dims, vals):
    total = 1
    for d in dims:
        total *= d
    assert len(vals) == total, (name, len(vals), total)
    ty = typ
    for d in reversed(dims):
        ty = f"[{ty}; {d}]"
    out.append(f"pub static {name}: {ty} = ")
    # nested literal
    def emit(vs, ds, indent):
        if len(ds) == 1:
            return "[" + ", ".join(str(v) for v in vs) + "]"
        step = len(vs) // ds[0]
        pad = "    " * (indent + 1)
        rows = [pad + emit(vs[i * step:(i + 1) * step], ds[1:], indent + 1) + "," for i in range(ds[0])]
        return "[\n" + "\n".join(rows) + "\n" + "    " * indent + "]"
    out[-1] += emit(vals, dims, 0) + ";\n"


arr("PRED4X4_PROB_INTRA", "u8", [10, 10, 9], nums(body(data, r"vp8_pred4x4_prob_intra\[10\]\[10\]\[9\]")))
arr("TOKEN_DEFAULT_PROBS", "u8", [4, 8, 3, 11], nums(body(data, r"vp8_token_default_probs\[4\]\[8\]\[3\]")))
arr("TOKEN_UPDATE_PROBS", "u8", [4, 8, 3, 11], nums(body(cdat, r"ff_vp8_token_update_probs\[4\]\[8\]\[3\]\[11\]")))
arr("DC_QLOOKUP", "u8", [128], nums(body(data, r"vp8_dc_qlookup\[")))
arr("AC_QLOOKUP", "u16", [128], nums(body(data, r"vp8_ac_qlookup\[")))
arr("MV_UPDATE_PROB", "u8", [2, 19], nums(body(data, r"vp8_mv_update_prob\[2\]\[19\]")))
arr("MV_DEFAULT_PROB", "u8", [2, 19], nums(body(data, r"vp8_mv_default_prob\[2\]\[19\]")))

print("// Generated by tools/gen_vp8_tables.py from FFmpeg's vp8data.h and vp8data.c.")
print("// Do not edit.")
print()
print("\n".join(out))
