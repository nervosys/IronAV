#!/usr/bin/env python3
"""Generate crates/ironav-codec/src/vorbis/tables.rs from FFmpeg's libavcodec/vorbis_data.c.

Usage: gen_vorbis_tables.py FFMPEG/libavcodec > tables.rs
"""
import os
import re
import sys

src = open(os.path.join(sys.argv[1], "vorbis_data.c"), encoding="utf-8").read()
m = re.search(r"ff_vorbis_floor1_inverse_db_table\[256\]\s*=\s*\{(.*?)\};", src, re.S)
vals = [v.strip().rstrip("Ff") for v in m.group(1).replace("\n", " ").split(",") if v.strip()]
assert len(vals) == 256, len(vals)
print("// Generated by tools/gen_vorbis_tables.py from FFmpeg's libavcodec/vorbis_data.c. Do not edit.")
print()
print("/// The floor 1 amplitude (0..=255) to linear gain table of the Vorbis specification.")
print("pub const FLOOR1_INVERSE_DB: [f32; 256] = [")
for i in range(0, 256, 4):
    print("    " + ", ".join(vals[i:i + 4]) + ",")
print("];")
