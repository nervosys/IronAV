const fn master(zeros: usize, ramp: &[u8]) -> [u8; 64] {
    let mut m = [64u8; 64];
    let mut i = 0;
    while i < zeros {
        m[i] = 0;
        i += 1;
    }
    let mut j = 0;
    while j < ramp.len() {
        m[zeros + j] = ramp[j];
        j += 1;
    }
    m
}

