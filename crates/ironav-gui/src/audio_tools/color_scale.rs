//! Standard waterfall scales in 8-bit sRGB.
//! The look-up tables come from Matplotlib 3.10.9 and OpenCV 4.12.0 (Parula).
//! ColorBrewer Spectral uses the reversed order. See COLORMAP-LICENSES.txt.

use eframe::egui::Color32;

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub(super) enum ColorScale {
    #[default]
    Jet,
    Parula,
    Spectral,
    Turbo,
    Viridis,
    Plasma,
    Inferno,
    Magma,
    Cividis,
    Greyscale,
}

impl ColorScale {
    pub(super) const ALL: [Self; 10] = [
        Self::Jet,
        Self::Parula,
        Self::Spectral,
        Self::Turbo,
        Self::Viridis,
        Self::Plasma,
        Self::Inferno,
        Self::Magma,
        Self::Cividis,
        Self::Greyscale,
    ];

    pub(super) fn name(self) -> &'static str {
        match self {
            Self::Jet => "Jet",
            Self::Parula => "Parula",
            Self::Spectral => "Spectral",
            Self::Turbo => "Turbo",
            Self::Viridis => "Viridis",
            Self::Plasma => "Plasma",
            Self::Inferno => "Inferno",
            Self::Magma => "Magma",
            Self::Cividis => "Cividis",
            Self::Greyscale => "Greyscale",
        }
    }

    pub(super) fn colors(self) -> &'static [Color32; 256] {
        match self {
            Self::Jet => &JET,
            Self::Parula => &PARULA,
            Self::Spectral => &SPECTRAL,
            Self::Turbo => &TURBO,
            Self::Viridis => &VIRIDIS,
            Self::Plasma => &PLASMA,
            Self::Inferno => &INFERNO,
            Self::Magma => &MAGMA,
            Self::Cividis => &CIVIDIS,
            Self::Greyscale => &GREYSCALE,
        }
    }
}

const fn from_rgb(values: [u32; 256]) -> [Color32; 256] {
    let mut colors = [Color32::BLACK; 256];
    let mut index = 0;
    while index < values.len() {
        let color = values[index];
        colors[index] = Color32::from_rgb((color >> 16) as u8, (color >> 8) as u8, color as u8);
        index += 1;
    }
    colors
}

const GREYSCALE: [Color32; 256] = {
    let mut colors = [Color32::BLACK; 256];
    let mut index = 0;
    while index < colors.len() {
        colors[index] = Color32::from_gray(index as u8);
        index += 1;
    }
    colors
};

